const STATE_NAMES = Object.keys(STATE_POINTS).sort((a, b) => b.length - a.length);

const normalize = (value) =>
  String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

const lookupKey = (raw) => {
  const key = normalize(raw);
  if (!key) return null;

  if (POINTS[key]) return POINTS[key];
  if (ALIASES[key] && POINTS[ALIASES[key]]) return POINTS[ALIASES[key]];
  if (STATE_POINTS[key]) return STATE_POINTS[key];

  const city = normalize(String(raw).split(",")[0]);
  if (city && POINTS[city]) return POINTS[city];
  if (city && ALIASES[city] && POINTS[ALIASES[city]]) return POINTS[ALIASES[city]];

  return null;
};

const isNonUsPlace = (values) => {
  const blob = values.map(normalize).join(" ");
  return NON_US_HINTS.some((hint) => blob.includes(hint));
};

const fallbackFromState = (values) => {
  const blob = values.map(normalize).join(" ");
  for (const state of STATE_NAMES) {
    if (blob.includes(state)) {
      return STATE_POINTS[state];
    }
  }
  return null;
};

const disambiguateWashington = (home) => {
  const short = normalize(home.shortLocation);
  const name = normalize(home.name);
  const location = normalize(home.location);

  if (short === "wash" || name.includes("huskies")) {
    return POINTS.seattle;
  }
  if (
    short === "wsh" ||
    short === "was" ||
    name.includes("commanders") ||
    name.includes("wizards") ||
    name.includes("nationals")
  ) {
    return POINTS.landover;
  }
  if (location === "washington" && home.stadiumCity) {
    return lookupKey(home.stadiumCity);
  }
  return null;
};

const asCoordinates = (point) =>
  point ? { lng: point[0], lat: point[1] } : null;

export const resolveGameMapLocation = (game = {}) => {
  const home = game?.competitors?.[1] || {};
  const away = game?.competitors?.[0] || {};
  const values = [
    home.stadiumCity,
    home.stadiumName,
    `${home.location} ${home.name}`,
    home.location,
    home.shortLocation,
    home.name,
    game.gameName,
    away.stadiumCity,
  ].filter(Boolean);

  if (isNonUsPlace(values)) {
    return asCoordinates(lookupKey(home.stadiumCity) || lookupKey(home.location));
  }

  const washington = disambiguateWashington(home);
  if (washington) {
    return asCoordinates(washington);
  }

  for (const value of values) {
    const point = lookupKey(value);
    if (point) {
      return asCoordinates(point);
    }
  }

  return asCoordinates(fallbackFromState(values));
};
